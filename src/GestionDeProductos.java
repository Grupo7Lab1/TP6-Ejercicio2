    private void jBGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBGuardarActionPerformed
        String descripcion = jTDescripcion.getText().trim();
        String precioTexto = jTPrecio.getText().trim();
        String categoriaTexto = (String) jCBCategoria.getSelectedItem();
        int stock = (int) jSpStock.getValue();

        if (descripcion.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "La descripción no puede estar vacía.",
                    "Error de validación",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (precioTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "El precio no puede estar vacío.",
                    "Error de validación",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        double precio;
        try {
            precio = Double.parseDouble(precioTexto.replace(",", "."));
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "El precio ingresado no es un número válido.",
                    "Error de validación",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (precio <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "El precio debe ser mayor a cero.",
                    "Error de validación",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        Rubro rubro;
        try {
            rubro = Rubro.valueOf(categoriaTexto.trim().toUpperCase());
        } catch (IllegalArgumentException ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Seleccioná una categoría válida.",
                    "Error de validación",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        int codigo = repositorio.listarTodos().size() + 1;

        Producto producto = new Producto(codigo, descripcion, precio, stock, rubro);
        repositorio.agregar(producto);

        refrescarTabla();

        jTCodigo.setText("");
        jTDescripcion.setText("");
        jTPrecio.setText("");
        jSpStock.setValue(0);
        jTDescripcion.requestFocus();

    }//GEN-LAST:event_jBGuardarActionPerformed
    private void refrescarTabla() {
        modeloProductos.setRowCount(0); // borra todas las filas actuales
        for (Producto p : repositorio.listarTodos()) {
            modeloProductos.addRow(new Object[]{
                p.getCodigo(), p.getDescripcion(), p.getPrecio(), p.getRubro(), p.getStock()
            });
        }
    }
