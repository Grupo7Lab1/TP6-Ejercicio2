    private void jTGestordeProductosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTGestordeProductosMouseClicked
        int filaSeleccionada = jTGestordeProductos.getSelectedRow();
        if (filaSeleccionada == -1) {
            return; // no hay ninguna fila seleccionada, no hacemos nada
        }
        int codigo = (int) modeloProductos.getValueAt(filaSeleccionada, 0);
        String descripcion = (String) modeloProductos.getValueAt(filaSeleccionada, 1);
        double precio = (double) modeloProductos.getValueAt(filaSeleccionada, 2);
        Rubro rubro = (Rubro) modeloProductos.getValueAt(filaSeleccionada, 3);
        int stock = (int) modeloProductos.getValueAt(filaSeleccionada, 4);
        jTCodigo.setText(String.valueOf(codigo));
        jTDescripcion.setText(descripcion);
        jTPrecio.setText(String.valueOf(precio));
        jCBCategoria.setSelectedItem(capitalizar(rubro.toString()));
        jSpStock.setValue(stock);
        jTCodigo.setEnabled(false); // el código no se debería poder editar
        jBGuardar.setEnabled(false);
        jBActualizar.setEnabled(true);
        jBEliminar.setEnabled(true);
    }//GEN-LAST:event_jTGestordeProductosMouseClicked

    private void jBEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBEliminarActionPerformed
        int filaSeleccionada = jTGestordeProductos.getSelectedRow();
        if (filaSeleccionada == -1) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Seleccioná un producto de la tabla para eliminar.",
                    "Aviso",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        int codigo = (int) modeloProductos.getValueAt(filaSeleccionada, 0);
        String descripcion = (String) modeloProductos.getValueAt(filaSeleccionada, 1);

        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this,
                "¿Seguro que querés eliminar el producto \"" + descripcion + "\"?",
                "Confirmar eliminación",
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.QUESTION_MESSAGE);
        if (confirmacion != javax.swing.JOptionPane.YES_OPTION) {
            return; // el usuario canceló
        }
        repositorio.eliminar(codigo);
        refrescarTabla();
        jTCodigo.setText("");
        jTDescripcion.setText("");
        jTPrecio.setText("");
        jSpStock.setValue(0);
        jTCodigo.setEnabled(true);
        jTDescripcion.setEnabled(false);
        jTPrecio.setEnabled(false);
        jCBCategoria.setEnabled(false);
        jSpStock.setEnabled(false);
        jBGuardar.setEnabled(false);
        jBActualizar.setEnabled(false);
        jBEliminar.setEnabled(false);
    }//GEN-LAST:event_jBEliminarActionPerformed
    private String capitalizar(String texto) {
        return texto.substring(0, 1).toUpperCase() + texto.substring(1).toLowerCase();
    }

